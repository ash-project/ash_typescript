defmodule AshTypescript.Codegen.SharedSchemaGenerator do
  @moduledoc """
  Generates a shared validation schema file for any `SchemaFormatter` implementation.

  Assembles all schemas into a single dedicated file:
  - Named schemas of declared custom types
  - Resource-level schemas (embedded resources, struct arguments)
  - Per-action RPC schemas
  - Per-route controller schemas
  """

  alias AshTypescript.Codegen.ImportResolver

  @doc """
  Generates the content for a shared schema file.

  ## Parameters

    * `formatter` - A module implementing `AshTypescript.Codegen.SchemaFormatter`
    * `opts` - A keyword list with:
      * `:resource_schemas` - Pre-generated resource schema string (required)
      * `:custom_type_schemas` - Pre-generated named custom-type schemas
        (`AshTypescript.Codegen.SchemaCore.generate_custom_type_schemas/1`),
        placed before the resource schemas so they can reference them (optional)
      * `:types_output_file` - Path to the shared types file (required)
      * `:schema_output_file` - Path to this schema file (required, for import resolution)
      * `:additional_schemas` - Pre-rendered schema strings to append (optional)
      * `:type_imports` - Type names the schemas reference, imported from the
        types file: the input types lazy resource schemas are cast to
        (`AshTypescript.Codegen.SchemaCore.recursive_resources/2`) (optional)

  ## Returns

  A string containing the TypeScript content for the shared schema file.
  """
  def generate(formatter, opts) do
    resource_schemas = Keyword.fetch!(opts, :resource_schemas)
    custom_type_schemas = Keyword.get(opts, :custom_type_schemas, "")
    types_output_file = Keyword.fetch!(opts, :types_output_file)
    schema_output_file = Keyword.fetch!(opts, :schema_output_file)
    additional_schemas = Keyword.get(opts, :additional_schemas, [])
    type_imports = Keyword.get(opts, :type_imports, [])

    import_path = formatter.configured_import_path()
    types_import_path = ImportResolver.resolve_import_path(schema_output_file, types_output_file)
    library_name = formatter.library_name()

    type_import_line =
      if type_imports != [] do
        "import type { #{Enum.join(type_imports, ", ")} } from \"#{types_import_path}\";\n"
      else
        ""
      end

    custom_import_lines = custom_import_lines(formatter, schema_output_file)

    leading_schemas =
      [custom_type_schemas, resource_schemas]
      |> Enum.reject(&(&1 == ""))
      |> Enum.join("\n")

    additional_section =
      additional_schemas
      |> Enum.reject(&(&1 == ""))
      |> Enum.join("\n")

    """
    // Generated by AshTypescript - Shared #{library_name} Schemas
    // Do not edit this file manually

    #{formatter.import_statement(import_path)}
    #{custom_import_lines}#{type_import_line}
    #{leading_schemas}

    #{additional_section}
    """
  end

  # User-authored imports for this formatter's file, so a `custom_types`
  # entry's `zod` / `valibot` can name a schema the user wrote in TypeScript. Scoped per library
  # (`zod_import_into_generated` / `valibot_import_into_generated`) rather than
  # reusing `import_into_generated`, which targets the types and RPC files and
  # would drag unrelated modules — and potential import cycles — in here.
  defp custom_import_lines(formatter, schema_output_file) do
    case ImportResolver.resolve_custom_imports(schema_output_file, formatter.custom_imports()) do
      "" -> ""
      lines -> lines <> "\n"
    end
  end
end
