defmodule AshTypescript.Codegen.SharedTypesGenerator do
  @moduledoc """
  Generates the shared TypeScript types file (`ash_types.ts`).

  Assembles type aliases, resource schemas, filter types, and utility types
  into a single file that both the RPC and typed controller files import from
  (`generate/1`). A project without RPC output gets only what its routes and
  typed channels files reference (`generate_standalone/1`).
  """

  import AshTypescript.Codegen
  import AshTypescript.Codegen.FilterTypes

  alias AshTypescript.Codegen.{
    CustomTypeAliases,
    Helpers,
    ImportResolver,
    SortTypes,
    TypeAliases,
    UtilityTypes
  }

  @doc """
  Generates the content for the shared types file.

  ## Parameters

    * `opts` - A keyword list with:
      * `:all_resources` - All resources needing schemas (required)
      * `:rpc_resources` - RPC-configured resources (required)
      * `:struct_argument_resources` - Resources used as struct arguments (default: [])
      * `:extra_alias_types` - Further `%Ash.Info.Manifest.Type{}` roots whose
        type aliases must be declared, e.g. typed channel payload types appended
        to the file (default: [])
      * `:route_types` - Typed controller route argument and result types,
        whose type aliases the routes file references (default: [])
      * `:types_output_file` - Path to the types output file, for resolving custom import paths (required)

  ## Returns

  A string containing the TypeScript content for the shared types file.
  """
  def generate(opts) do
    all_resources = Keyword.fetch!(opts, :all_resources)
    rpc_resources = Keyword.fetch!(opts, :rpc_resources)
    struct_argument_resources = Keyword.get(opts, :struct_argument_resources, [])
    extra_alias_types = Keyword.get(opts, :extra_alias_types, [])
    route_types = Keyword.get(opts, :route_types, [])
    types_output_file = Keyword.fetch!(opts, :types_output_file)

    custom_imports = generate_custom_imports(types_output_file)
    resource_lookup = AshTypescript.resource_lookup()

    filter_sort_resources =
      Enum.filter(all_resources, &Helpers.filter_and_sort_types?(Map.fetch!(resource_lookup, &1)))

    type_aliases =
      TypeAliases.generate_ash_type_aliases(rpc_resources, resource_lookup, extra_alias_types,
        route_types: route_types,
        struct_argument_resources: struct_argument_resources
      )

    """
    // Generated by AshTypescript - Shared Types
    // Do not edit this file manually

    #{custom_imports}

    #{type_aliases}

    #{generate_all_schemas_for_resources(all_resources, all_resources, struct_argument_resources)}

    #{generate_filter_types(filter_sort_resources, all_resources, resource_lookup)}

    #{generate_filter_field_arrays(filter_sort_resources, resource_lookup)}

    #{SortTypes.generate_sort_types(filter_sort_resources, resource_lookup)}

    #{UtilityTypes.generate_utility_types()}
    """
  end

  @doc """
  Generates the shared types file for a project without RPC output: what the
  routes and typed channels files reference, and nothing else (no resource
  schemas, filter, sort or utility types; route arguments and results and
  channel payloads are plain data, so they reach no resource).

  The file holds the custom imports, the aliases the route types and the
  `:extra_alias_types` reach (`TypeAliases.generate_aliases_for_roots/2`,
  with the aliased definitions of `CustomTypeAliases.reachable/1`), and the
  `:channel_types` content.

  ## Parameters

    * `opts` - A keyword list with:
      * `:route_types` - Typed controller route argument and result types (default: [])
      * `:extra_alias_types` - Further `%Ash.Info.Manifest.Type{}` roots, e.g.
        typed channel payload types (default: [])
      * `:channel_types` - The typed channel types content, appended (default: "")
      * `:types_output_file` - Path to the types output file, for resolving custom import paths (required)

  ## Returns

  The TypeScript content, or `""` when there are no aliases or channel types
  to declare.
  """
  def generate_standalone(opts) do
    roots =
      Keyword.get(opts, :route_types, []) ++ Keyword.get(opts, :extra_alias_types, [])

    channel_types = Keyword.get(opts, :channel_types, "")
    types_output_file = Keyword.fetch!(opts, :types_output_file)

    type_aliases =
      TypeAliases.generate_aliases_for_roots(roots, CustomTypeAliases.reachable(roots))

    if type_aliases == "" and channel_types == "" do
      ""
    else
      content = """
      // Generated by AshTypescript - Shared Types
      // Do not edit this file manually

      #{generate_custom_imports(types_output_file)}

      #{type_aliases}
      """

      if channel_types == "", do: content, else: content <> "\n" <> channel_types
    end
  end

  defp generate_custom_imports(target_output_file) do
    case Application.get_env(:ash_typescript, :import_into_generated) do
      nil ->
        ""

      imports when is_list(imports) ->
        ImportResolver.resolve_custom_imports(target_output_file, imports)

      _ ->
        ""
    end
  end
end
