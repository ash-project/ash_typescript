defmodule AshTypescript.Codegen.NoRpcTypesFileTest do
  # Without `output_file`, the shared types file holds exactly what the
  # routes and typed channels files reference (aliases, the schemas of the
  # embedded resources they reach, the channel types), and they import it
  # as in RPC projects. Nothing shared: no types file and no re-export.
  # Codegen returns the files without writing them, so the configured
  # paths are used as they are.
  use ExUnit.Case, async: false

  import AshTypescript.Test.CodegenTestHelper,
    only: [generate_files: 2, routes_content: 1, typed_channels_content: 1, types_content: 1]

  alias AshTypescript.Codegen.NoRpcTypesFileTest, as: T
  alias AshTypescript.Test.InlineManifest

  @env_keys [
    :output_file,
    :types_output_file,
    :zod_output_file,
    :valibot_output_file,
    :routes_output_file,
    :typed_channels_output_file,
    :enable_namespace_files,
    :enable_controller_namespace_files,
    :router
  ]

  @types_file "./test/ts/ash_types.ts"

  defmodule Inner do
    @moduledoc false
    use Ash.Resource, data_layer: :embedded

    attributes do
      attribute :seen_at, :utc_datetime_usec, public?: true
    end
  end

  defmodule Outer do
    @moduledoc false
    use Ash.Resource, data_layer: :embedded

    attributes do
      attribute :label, :string, public?: true
      attribute :inner, AshTypescript.Codegen.NoRpcTypesFileTest.Inner, public?: true
    end
  end

  defmodule AliasController do
    @moduledoc false
    use AshTypescript.TypedController

    typed_controller do
      module_name AshTypescript.Codegen.NoRpcTypesFileTest.AliasControllerImpl

      post :record do
        run fn conn, _params -> Plug.Conn.send_resp(conn, 200, "") end
        argument :code, AshTypescript.Test.CustomIdentifier
        argument :amount, :decimal
        returns AshTypescript.Test.TaskStats
      end
    end
  end

  defmodule NestedController do
    @moduledoc false
    use AshTypescript.TypedController

    typed_controller do
      module_name AshTypescript.Codegen.NoRpcTypesFileTest.NestedControllerImpl

      post :store do
        run fn conn, _params -> Plug.Conn.send_resp(conn, 200, "") end
        argument :outers, {:array, AshTypescript.Codegen.NoRpcTypesFileTest.Outer}
      end
    end
  end

  defmodule StructController do
    @moduledoc false
    use AshTypescript.TypedController

    typed_controller do
      module_name AshTypescript.Codegen.NoRpcTypesFileTest.StructControllerImpl

      post :upload do
        run fn conn, _params -> Plug.Conn.send_resp(conn, 200, "") end
        argument :todo, :struct, constraints: [instance_of: AshTypescript.Test.Todo]
      end
    end
  end

  defmodule PlainController do
    @moduledoc false
    use AshTypescript.TypedController

    typed_controller do
      module_name AshTypescript.Codegen.NoRpcTypesFileTest.PlainControllerImpl

      post :ping do
        run fn conn, _params -> Plug.Conn.send_resp(conn, 200, "") end
        argument :name, :string
        argument :count, :integer
      end
    end
  end

  setup do
    AshTypescript.Test.TestHelpers.restore_application_env_on_exit(@env_keys)
    Application.put_env(:ash_typescript, :types_output_file, @types_file)
    Application.put_env(:ash_typescript, :enable_namespace_files, false)
    Application.put_env(:ash_typescript, :enable_controller_namespace_files, false)
    :ok
  end

  defp without_rpc_output, do: Application.delete_env(:ash_typescript, :output_file)

  # Test-file controllers aren't in the test router: render their routes
  # without one.
  defp without_router, do: Application.put_env(:ash_typescript, :router, nil)

  defp exported?(types, name), do: types =~ ~r/^export type #{name}\b/m

  describe "the app manifest without RPC output" do
    setup do
      without_rpc_output()
      {:ok, files} = generate_files(:ash_typescript, [])

      %{
        files: files,
        types: types_content(files),
        routes: routes_content(files),
        channels: typed_channels_content(files)
      }
    end

    test "the routes file's shared names are generated and imported", %{
      types: types,
      routes: routes
    } do
      for name <- ~w(UUID UtcDateTime TaskMetadataInputSchema), do: assert(exported?(types, name))

      assert routes =~
               ~s(import type { TaskMetadataInputSchema, UUID, UtcDateTime } from "./ash_types";\n) <>
                 ~s(export type * from "./ash_types";)
    end

    test "the types file holds only what the routes and channels files reach", %{types: types} do
      assert types =~ "// Generated by AshTypescript - Shared Types"
      refute types =~ "TodoResourceSchema"
      refute types =~ "FilterInput"
      refute types =~ "InferResult"
      refute exported?(types, "LineItem")
      refute exported?(types, "Decimal")
    end

    test "typed channels import their payload and channel types from it", %{
      types: types,
      channels: channels
    } do
      for name <- ~w(ContentFeedChannel ContentFeedChannelEvents AlertSentPayload),
          do: assert(exported?(types, name))

      assert channels =~
               ~r/^import type \{ [^}]*\bContentFeedChannel\b[^}]*\} from "\.\/ash_types";$/m

      assert channels =~ ~s(export type * from "./ash_types";)
    end
  end

  describe "a route reaching aliases" do
    setup do
      without_rpc_output()
      without_router()
      manifest = InlineManifest.build!(typed_controllers: [T.AliasController])
      {:ok, files} = generate_files(:ash_typescript, manifest: manifest)
      %{types: types_content(files), routes: routes_content(files)}
    end

    test "scalar, primitive and map-like aliases a route reaches are included", %{
      types: types,
      routes: routes
    } do
      assert types =~ "export type CustomIdentifier = string;\n"
      assert types =~ "export type Decimal = string;\n"
      assert types =~ ~r/^export type TaskStats = \{/m
      refute exported?(types, "UUID")
      refute exported?(types, "GeoPoint")

      assert routes =~
               ~r/^import type \{ [^}]*\bCustomIdentifier\b[^}]*\} from "\.\/ash_types";$/m
    end
  end

  describe "a route reaching nested embedded resources" do
    setup do
      without_rpc_output()
      without_router()
      manifest = InlineManifest.build!(typed_controllers: [T.NestedController])
      {:ok, files} = generate_files(:ash_typescript, manifest: manifest)
      %{types: types_content(files), routes: routes_content(files)}
    end

    test "the schemas of the embedded resources it reaches, transitively, and their aliases", %{
      types: types,
      routes: routes
    } do
      prefix = "AshTypescriptCodegenNoRpcTypesFileTest"

      for name <- ["#{prefix}OuterInputSchema", "#{prefix}InnerInputSchema", "UtcDateTimeUsec"],
          do: assert(exported?(types, name), "#{name} not exported")

      assert routes =~ "#{prefix}OuterInputSchema"
    end
  end

  describe "a route with a resource struct argument" do
    setup do
      without_rpc_output()
      without_router()
      manifest = InlineManifest.build!(typed_controllers: [T.StructController])
      {:ok, files} = generate_files(:ash_typescript, manifest: manifest)
      %{types: types_content(files), routes: routes_content(files)}
    end

    test "the resource's input schema, what its attributes reach, and no output schemas", %{
      types: types,
      routes: routes
    } do
      assert routes =~ "TodoInputSchema"
      assert routes =~ ~r/^import type \{ [^}]*\bTodoInputSchema\b[^}]*\} from "\.\/ash_types";$/m

      # `TodoMetadata` is an embedded attribute of `Todo`; `UtcDateTimeUsec`
      # is `Todo.created_at`'s alias.
      for name <- ~w(TodoInputSchema TodoMetadataInputSchema UtcDateTimeUsec),
          do: assert(exported?(types, name), "#{name} not exported")

      refute types =~ "TodoResourceSchema"
      refute types =~ "TodoAttributesOnlySchema"
    end
  end

  describe "nothing shared" do
    setup do
      without_rpc_output()
      without_router()
      manifest = InlineManifest.build!(typed_controllers: [T.PlainController])
      {:ok, files} = generate_files(:ash_typescript, manifest: manifest)
      %{files: files, routes: routes_content(files)}
    end

    test "no types file and no re-export", %{files: files, routes: routes} do
      refute Map.has_key?(files, @types_file)
      assert routes =~ "ping"
      refute routes =~ "ash_types"
    end
  end

  test "RPC projects keep the full types file" do
    {:ok, files} = generate_files(:ash_typescript, [])
    types = types_content(files)

    for name <- ~w(TodoResourceSchema TodoFilterInput InferResult LineItem),
        do: assert(exported?(types, name), "#{name} not exported")

    assert routes_content(files) =~ ~s(export type * from "./ash_types";)
  end
end
