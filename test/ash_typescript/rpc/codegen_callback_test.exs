defmodule AshTypescript.Rpc.CodegenCallbackTest do
  # `mix ash.codegen` calls each extension's `codegen/1`; the Rpc extension's
  # runs `mix ash_typescript.codegen` with the same arguments, and can run
  # again in the same session.
  use ExUnit.Case, async: false

  import ExUnit.CaptureIO

  setup do
    # `--output` sets `output_file` for the rest of the session.
    AshTypescript.Test.TestHelpers.restore_application_env_on_exit([:output_file])
  end

  @tag :tmp_dir
  test "codegen/1 runs ash_typescript.codegen with its arguments, every time", %{
    tmp_dir: tmp_dir
  } do
    # A dry run prints the files that would change: none exist in `tmp_dir`.
    for _ <- 1..2 do
      output =
        capture_io(fn -> AshTypescript.Rpc.codegen(["--dry-run", "--output", tmp_dir]) end)

      assert output =~
               "##{Path.join(tmp_dir, "ash_rpc.ts")}:\n\n// Generated by AshTypescript - RPC Actions"
    end
  end
end
